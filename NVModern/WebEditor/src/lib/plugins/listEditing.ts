import {
  deleteMarkupBackward,
  insertNewlineContinueMarkupCommand,
  markdownLanguage,
} from "@codemirror/lang-markdown";
import { ensureSyntaxTree, syntaxTree } from "@codemirror/language";
import {
  EditorState,
  Prec,
  Transaction,
  type ChangeSpec,
  type Extension,
  type StateCommand,
  type TransactionSpec,
} from "@codemirror/state";
import { keymap } from "@codemirror/view";
import type { SyntaxNode } from "@lezer/common";

/**
 * Markdown list editing policy for nvModern.
 *
 * This file intentionally treats lists as a tree-shaped structure rather than a
 * loose collection of line prefixes.
 *
 * Invariants enforced here:
 * - Nested list indentation generated by the editor is always 4 spaces.
 * - Four leading spaces are not treated as Markdown code blocks in nvModern.
 * - Ordered lists are normalized after structural edits so sibling numbering is
 *   sequential again.
 * - Indent/outdent operate on the current list item subtree (the item's own
 *   line(s) plus any nested children), not just the first marker line.
 * - Indenting an ordered item under a previous sibling restarts numbering at 1
 *   in the new nested ordered list, and renumbers existing siblings at that
 *   level.
 * - Outdenting an ordered item renumbers both the source and destination list
 *   levels.
 *
 * Interaction model:
 * - Enter: continue Markdown markup with CodeMirror's built-in command, then let
 *   the transaction filter renumber affected ordered lists.
 * - Backspace: use CodeMirror's Markdown-aware deletion command, then let the
 *   transaction filter renumber affected ordered lists.
 * - Tab: if the selection is inside list items, indent those items one level
 *   deeper using 4 spaces.
 * - Shift-Tab: if the selection is inside list items, outdent those items one
 *   level.
 *
 * Regression guardrails:
 * - Keep this file focused on editing semantics. Rendering stays in
 *   `listPrefixes.ts`.
 * - Prefer minimal source edits: renumber only marker digits when possible.
 * - If a future change makes numbering depend on ad-hoc heuristics instead of
 *   the parsed tree, that is likely a regression.
 * - If a future change only shifts the first line of an item, that is likely a
 *   regression.
 *
 * Future enhancement (not implemented here):
 * - Add an explicit "normalize existing list block" command that rewrites an
 *   already-authored list selection/block to the canonical nvModern style.
 */
const LIST_INDENT = "    ";
const LIST_INDENT_WIDTH = LIST_INDENT.length;
const ORDERED_LIST_NAME = "OrderedList";
const LIST_ITEM_NAME = "ListItem";
const LIST_MARK_NAME = "ListMark";
const LIST_CONTAINER_NAMES = new Set(["BulletList", ORDERED_LIST_NAME]);
const BLOCKQUOTE_PREFIX_PATTERN = /^(?:[\t ]{0,3}> ?)+/;
const continueMarkup = insertNewlineContinueMarkupCommand({ nonTightLists: true });

function clampDocPosition(doc: EditorState["doc"], pos: number): number {
  return Math.max(0, Math.min(pos, doc.length));
}

function nodeName(node: SyntaxNode | null): string {
  return node?.type.name ?? "";
}

function isListContainer(node: SyntaxNode | null): boolean {
  return LIST_CONTAINER_NAMES.has(nodeName(node));
}

function findAncestor(node: SyntaxNode | null, predicate: (node: SyntaxNode) => boolean): SyntaxNode | null {
  let cursor = node;

  while (cursor) {
    if (predicate(cursor)) return cursor;
    cursor = cursor.parent;
  }

  return null;
}

function resolveNode(state: EditorState, pos: number, bias = -1): SyntaxNode {
  return syntaxTree(state).resolveInner(clampDocPosition(state.doc, pos), bias);
}

function isMarkdownEditingPosition(state: EditorState, pos: number): boolean {
  const clamped = clampDocPosition(state.doc, pos);
  return markdownLanguage.isActiveAt(state, clamped, -1) || markdownLanguage.isActiveAt(state, clamped, 1);
}

function findEnclosingListItem(state: EditorState, pos: number): SyntaxNode | null {
  if (!isMarkdownEditingPosition(state, pos)) return null;

  const resolved = resolveNode(state, pos, pos > 0 ? -1 : 1);
  return findAncestor(resolved, (node) => nodeName(node) === LIST_ITEM_NAME);
}

function previousListItemSibling(node: SyntaxNode): SyntaxNode | null {
  let cursor = node.prevSibling;

  while (cursor) {
    if (nodeName(cursor) === LIST_ITEM_NAME) return cursor;
    cursor = cursor.prevSibling;
  }

  return null;
}

function computeListDepth(node: SyntaxNode): number {
  let depth = -1;
  let cursor: SyntaxNode | null = node;

  while (cursor) {
    if (isListContainer(cursor)) {
      depth += 1;
    }
    cursor = cursor.parent;
  }

  return Math.max(0, depth);
}

function lineNumberAtNodeEnd(state: EditorState, node: SyntaxNode): number {
  if (state.doc.length === 0) return 1;

  const clampedTo = clampDocPosition(state.doc, node.to);
  const pos = clampedTo === 0 ? 0 : clampedTo === state.doc.length ? clampedTo : clampedTo - 1;
  return state.doc.lineAt(pos).number;
}

function listItemLineNumbers(state: EditorState, node: SyntaxNode): { fromLine: number; toLine: number } {
  return {
    fromLine: state.doc.lineAt(node.from).number,
    toLine: lineNumberAtNodeEnd(state, node),
  };
}

function blockquotePrefixLength(text: string): number {
  return text.match(BLOCKQUOTE_PREFIX_PATTERN)?.[0].length ?? 0;
}

function removableIndentLength(text: string, start: number): number {
  let pos = start;
  let width = 0;

  while (pos < text.length && width < LIST_INDENT_WIDTH) {
    const char = text.charAt(pos);
    if (char === " ") {
      pos += 1;
      width += 1;
      continue;
    }

    if (char === "\t") {
      pos += 1;
      width = LIST_INDENT_WIDTH;
      break;
    }

    break;
  }

  return pos - start;
}

function buildIndentChangesForItem(state: EditorState, item: SyntaxNode): ChangeSpec[] {
  const { fromLine, toLine } = listItemLineNumbers(state, item);
  const changes: ChangeSpec[] = [];

  for (let lineNo = fromLine; lineNo <= toLine; lineNo += 1) {
    const line = state.doc.line(lineNo);
    if (line.length === 0) continue;

    const insertAt = line.from + blockquotePrefixLength(line.text);
    changes.push({ from: insertAt, insert: LIST_INDENT });
  }

  return changes;
}

function buildOutdentChangesForItem(state: EditorState, item: SyntaxNode): ChangeSpec[] | null {
  if (computeListDepth(item) === 0) return null;

  const { fromLine, toLine } = listItemLineNumbers(state, item);
  const changes: ChangeSpec[] = [];

  for (let lineNo = fromLine; lineNo <= toLine; lineNo += 1) {
    const line = state.doc.line(lineNo);
    if (line.length === 0) continue;

    const removeFrom = line.from + blockquotePrefixLength(line.text);
    const removeLength = removableIndentLength(line.text, removeFrom - line.from);

    if (removeLength === 0) {
      return null;
    }

    changes.push({ from: removeFrom, to: removeFrom + removeLength });
  }

  return changes;
}

function collectSelectedListItems(state: EditorState): SyntaxNode[] {
  const items: SyntaxNode[] = [];

  for (const range of state.selection.ranges) {
    const item = findEnclosingListItem(state, range.head);
    if (item) {
      items.push(item);
    }
  }

  if (items.length <= 1) return items;

  items.sort((left, right) => left.from - right.from || right.to - left.to);

  const deduped: SyntaxNode[] = [];
  for (const item of items) {
    const alreadyCovered = deduped.some((existing) => item.from >= existing.from && item.to <= existing.to);
    if (!alreadyCovered) {
      deduped.push(item);
    }
  }

  return deduped;
}

function applyListItemIndentation(
  state: EditorState,
  dispatch: ((tr: Transaction) => void) | undefined,
  direction: "indent" | "outdent",
): boolean {
  const selectedItems = collectSelectedListItems(state);
  if (selectedItems.length === 0) return false;

  const relevantItems =
    direction === "indent"
      ? selectedItems.filter((item) => previousListItemSibling(item))
      : selectedItems;

  if (relevantItems.length === 0) return false;

  const changes: ChangeSpec[] = [];

  for (const item of relevantItems) {
    if (direction === "indent") {
      changes.push(...buildIndentChangesForItem(state, item));
      continue;
    }

    const outdentChanges = buildOutdentChangesForItem(state, item);
    if (!outdentChanges) continue;
    changes.push(...outdentChanges);
  }

  if (changes.length === 0) return false;

  changes.sort((left, right) => {
    const leftFrom = left.from;
    const rightFrom = right.from;
    if (leftFrom !== rightFrom) return leftFrom - rightFrom;

    const leftTo = "to" in left && typeof left.to === "number" ? left.to : leftFrom;
    const rightTo = "to" in right && typeof right.to === "number" ? right.to : rightFrom;
    return leftTo - rightTo;
  });

  dispatch?.(
    state.update({
      changes,
      scrollIntoView: true,
      userEvent: direction === "indent" ? "input.indent" : "delete.dedent",
    }),
  );

  return true;
}

export const indentMarkdownListItem: StateCommand = ({ state, dispatch }) =>
  applyListItemIndentation(state, dispatch, "indent");

export const outdentMarkdownListItem: StateCommand = ({ state, dispatch }) =>
  applyListItemIndentation(state, dispatch, "outdent");

function addOrderedListCandidate(target: Map<string, SyntaxNode>, node: SyntaxNode | null): void {
  const orderedList = findAncestor(node, (candidate) => nodeName(candidate) === ORDERED_LIST_NAME);
  if (!orderedList) return;

  target.set(`${orderedList.from}:${orderedList.to}`, orderedList);
}

function collectAffectedOrderedLists(state: EditorState, transaction: Transaction): SyntaxNode[] {
  const doc = state.doc;
  if (doc.length === 0) return [];

  const candidates = new Map<string, SyntaxNode>();
  let maxTo = 0;

  transaction.changes.iterChangedRanges((_fromA, _toA, fromB, toB) => {
    const rangeStart = clampDocPosition(doc, fromB);
    const rangeEnd = clampDocPosition(doc, toB > fromB ? toB - 1 : toB);
    const startLine = doc.lineAt(rangeStart).number;
    const endLine = doc.lineAt(rangeEnd).number;
    const expandedStartLine = Math.max(1, startLine - 1);
    const expandedEndLine = Math.min(doc.lines, endLine + 1);
    const from = doc.line(expandedStartLine).from;
    const to = doc.line(expandedEndLine).to;

    maxTo = Math.max(maxTo, to);
    addOrderedListCandidate(candidates, resolveNode(state, from, 1));
    addOrderedListCandidate(candidates, resolveNode(state, to, -1));
  });

  if (maxTo > 0) {
    ensureSyntaxTree(state, maxTo, 100);
  }

  const tree = syntaxTree(state);
  transaction.changes.iterChangedRanges((_fromA, _toA, fromB, toB) => {
    const rangeStart = clampDocPosition(doc, fromB);
    const rangeEnd = clampDocPosition(doc, toB > fromB ? toB - 1 : toB);
    const startLine = doc.lineAt(rangeStart).number;
    const endLine = doc.lineAt(rangeEnd).number;
    const expandedStartLine = Math.max(1, startLine - 1);
    const expandedEndLine = Math.min(doc.lines, endLine + 1);
    const from = doc.line(expandedStartLine).from;
    const to = doc.line(expandedEndLine).to;

    tree.iterate({
      from,
      to,
      enter(node) {
        if (node.name !== ORDERED_LIST_NAME) return;
        candidates.set(`${node.from}:${node.to}`, node.node);
      },
    });
  });

  return [...candidates.values()].sort((left, right) => left.from - right.from || left.to - right.to);
}

function orderedListMarkerDigits(mark: SyntaxNode, state: EditorState): { from: number; to: number; value: number } | null {
  const markerText = state.doc.sliceString(mark.from, mark.to);
  const match = markerText.match(/^(\d+)([.)])$/);
  if (!match) return null;

  const digits = match[1] ?? "";
  return {
    from: mark.from,
    to: mark.from + digits.length,
    value: Number(digits),
  };
}

function buildOrderedListRenumberChanges(state: EditorState, lists: readonly SyntaxNode[]): ChangeSpec[] {
  if (lists.length === 0) return [];

  const maxTo = lists.reduce((max, node) => Math.max(max, node.to), 0);
  if (maxTo > 0) {
    ensureSyntaxTree(state, maxTo, 150);
  }

  const changes: ChangeSpec[] = [];

  for (const list of lists) {
    let expected = 1;

    for (let child = list.firstChild; child; child = child.nextSibling) {
      if (nodeName(child) !== LIST_ITEM_NAME) continue;

      const mark = child.getChild(LIST_MARK_NAME);
      if (!mark) {
        expected += 1;
        continue;
      }

      const marker = orderedListMarkerDigits(mark, state);
      if (!marker) {
        expected += 1;
        continue;
      }

      if (marker.value !== expected) {
        changes.push({
          from: marker.from,
          to: marker.to,
          insert: String(expected),
        });
      }

      expected += 1;
    }
  }

  changes.sort((left, right) => {
    const leftFrom = left.from;
    const rightFrom = right.from;
    if (leftFrom !== rightFrom) return leftFrom - rightFrom;

    const leftTo = "to" in left && typeof left.to === "number" ? left.to : leftFrom;
    const rightTo = "to" in right && typeof right.to === "number" ? right.to : rightFrom;
    return leftTo - rightTo;
  });

  return changes;
}

function transactionAsSpec(transaction: Transaction): TransactionSpec {
  return transaction as unknown as TransactionSpec;
}

function normalizeOrderedLists(transaction: Transaction): TransactionSpec | readonly TransactionSpec[] {
  if (!transaction.docChanged) return transactionAsSpec(transaction);

  const nextState = transaction.state;
  const orderedLists = collectAffectedOrderedLists(nextState, transaction);
  if (orderedLists.length === 0) return transactionAsSpec(transaction);

  const changes = buildOrderedListRenumberChanges(nextState, orderedLists);
  if (changes.length === 0) return transactionAsSpec(transaction);

  return [transactionAsSpec(transaction), { changes, sequential: true }];
}

export function createMarkdownListEditingExtension(): Extension {
  return [
    Prec.high(
      keymap.of([
        { key: "Enter", run: continueMarkup },
        { key: "Backspace", run: deleteMarkupBackward },
        { key: "Tab", run: indentMarkdownListItem },
        { key: "Shift-Tab", run: outdentMarkdownListItem },
      ]),
    ),
    EditorState.transactionFilter.of((transaction) => normalizeOrderedLists(transaction)),
  ];
}
